'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const {createHash,randomUUID}=require('node:crypto');
const root=path.resolve(__dirname,'..');
const source=path.join(root,'wiki-demo-mvp');
const html=fs.readFileSync(path.join(source,'index.html'),'utf8');
const pipeline=fs.readFileSync(path.join(source,'pipeline.js'),'utf8');
const start=html.indexOf('const DEFAULT_PROMPTS={');
const end=html.indexOf('const promptHistoryOriginalDefaults=',start);
const cutoff=pipeline.indexOf('function stopAllModelRequests(');
assert.ok(start>=0&&end>start&&cutoff>0,'默认定义或顶部升级边界未找到');
const storage=new Map();
const sandbox={structuredClone,TextEncoder,WEAK_PROMPTS:{},promptLabels:{},STORE:'wiki_preview_v1_',state:{prompts:{},baselinePrompts:{}},localStorage:{getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value)},save:(key,value)=>storage.set(key,JSON.stringify(value)),setTimeout:()=>{throw Error('默认升级不应触发异步逻辑')},toast:()=>{throw Error('默认升级不应触发错误提示')}};
vm.createContext(sandbox);
vm.runInContext(html.slice(start,end),sandbox,{timeout:1000,filename:'index.html:DEFAULT_PROMPTS'});
vm.runInContext(pipeline.slice(0,cutoff),sandbox,{timeout:1000,filename:'pipeline.js:默认升级'});
const defaults=JSON.parse(vm.runInContext('JSON.stringify(DEFAULT_PROMPTS)',sandbox));
const steps=['step2','step3','step4','step5','integration'];
assert.deepEqual(Object.keys(defaults).sort(),[...steps].sort());
const snapshot={baseline:structuredClone(defaults),current:structuredClone(defaults)};
for(const side of ['baseline','current'])for(const step of steps){const value=snapshot[side][step];assert.equal(typeof value,'string');assert.ok(value.trim()&&[...value].length<=50000&&!value.includes('\u0000'));}
assert.deepEqual(snapshot.baseline,snapshot.current);
assert.deepEqual(JSON.parse(vm.runInContext('JSON.stringify(state.prompts)',sandbox)),defaults);
assert.deepEqual(JSON.parse(vm.runInContext('JSON.stringify(state.baselinePrompts)',sandbox)),defaults);
assert.ok(snapshot.current.step5.includes('不可覆盖的主类型与语义分面门禁'));
assert.ok(snapshot.current.step2.includes('分段仅提炼候选'));
assert.ok(snapshot.current.step3.includes('候选按价值准入'));
assert.ok(!JSON.stringify(snapshot).includes('74'));
const bytes=Buffer.byteLength(JSON.stringify(snapshot),'utf8');assert.ok(bytes<700000);
const output=path.join(root,'outputs/wiki-prompt-history-initial-snapshot.json');
assert.ok(!fs.existsSync(output),'专项快照已存在，停止以免覆盖');
fs.writeFileSync(output,JSON.stringify(snapshot,null,2)+'\n',{flag:'wx'});
assert.deepEqual(JSON.parse(fs.readFileSync(output,'utf8')),snapshot);
const hash=text=>createHash('sha256').update(text).digest('hex');
const files=['index.html','pipeline.js','semantic-tags.js','file-manager.js','prompt-history.js'];
const proof={applicationId:'wbapp_lEfhf5ImEBOz2gSHB2VcGl',request_id:randomUUID(),generatedAt:new Date().toISOString(),sourceMode:'当前 DEFAULT_PROMPTS + pipeline 顶部默认升级；空模拟存储；未读取 custom',sourceHashes:Object.fromEntries(files.map(file=>[file,hash(fs.readFileSync(path.join(source,file)))])),snapshotSha256:hash(JSON.stringify(snapshot)),snapshotBytes:bytes,steps:Object.fromEntries(steps.map(step=>[step,{characters:[...defaults[step]].length,sha256:hash(defaults[step])}]))};
fs.writeFileSync(path.join(root,'outputs/wiki-prompt-history-initial-validation.json'),JSON.stringify(proof,null,2)+'\n',{flag:'wx'});
